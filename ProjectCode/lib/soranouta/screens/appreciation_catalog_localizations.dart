  if (selected == SupportedLanguage.zhHans) return source;
  final values = _catalogTranslations[source];
  if (values == null) return source;
  return switch (selected) {
    SupportedLanguage.en => values[0],
    SupportedLanguage.ja => values[1],
    SupportedLanguage.ko => values[2],
    SupportedLanguage.zhHant => values[3],
    SupportedLanguage.zhHans => source,
  };
}

